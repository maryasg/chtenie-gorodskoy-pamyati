PITCH_PDF = "docs/presentation/pitch/Презентация_Читать_стены.pdf"


def add_slide(doc, number, title, on_screen=None, speech=None, notes=None):
    doc.add_heading(f"Слайд {number}. {title}", level=1)

    if on_screen:
        p = doc.add_paragraph()
        run = p.add_run("Текст на слайде (ориентир)")
        run.bold = True
        for line in on_screen:
            doc.add_paragraph(line, style="List Bullet")

    if speech:
        p = doc.add_paragraph()
        run = p.add_run("Речь")
        run.bold = True
        for para in speech:
            doc.add_paragraph(para)

    if notes:
        p = doc.add_paragraph()
        run = p.add_run("Заметки докладчику")
        run.bold = True
        run.italic = True
        for line in notes:
            doc.add_paragraph(line, style="List Bullet")

    doc.add_paragraph()


def add_appendix(doc, title, on_screen=None, speech=None, notes=None):
    doc.add_heading(f"Приложение. {title}", level=1)
    note = doc.add_paragraph(
        "Этих слайдов пока нет в PDF «Презентация_Читать_стены». "
        "Можно добавить в презентацию позже или сказать устно со слайда 16–17."
    )
    note.runs[0].italic = True
    doc.add_paragraph()

    if on_screen:
        p = doc.add_paragraph()
        run = p.add_run("Вариант текста на слайд")
        run.bold = True
        for line in on_screen:
            doc.add_paragraph(line, style="List Bullet")

    if speech:
        p = doc.add_paragraph()
        run = p.add_run("Речь")
        run.bold = True
        for para in speech:
            doc.add_paragraph(para)

    if notes:
        p = doc.add_paragraph()
        run = p.add_run("Заметки")
        run.bold = True
        run.italic = True
        for line in notes:
            doc.add_paragraph(line, style="List Bullet")

    doc.add_paragraph()


