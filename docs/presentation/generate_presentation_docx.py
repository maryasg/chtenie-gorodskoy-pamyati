def add_slide(doc, number, title, on_screen=None, speech=None, notes=None):
    doc.add_heading(f"Слайд {number}. {title}", level=1)

    if on_screen:
        p = doc.add_paragraph()
        run = p.add_run("Текст на экране")
        run.bold = True
        for line in on_screen:
            doc.add_paragraph(line, style="List Bullet")

    if speech:
        p = doc.add_paragraph()
        run = p.add_run("Речь")
        run.bold = True
        for para in speech:
            doc.add_paragraph(para)

    if notes:
        p = doc.add_paragraph()
        run = p.add_run("Заметки докладчику")
        run.bold = True
        run.italic = True
        for line in notes:
            doc.add_paragraph(line, style="List Bullet")

    doc.add_paragraph()


