def month_to_items(month: str, titles: list[str]) -> list[dict]:
    return [
        {"month": month, "number": f"{i:02d}", "title": title}
        for i, title in enumerate(titles, start=1)
    ]


def main() -> None:
    OUT_DIR.mkdir(exist_ok=True)
    all_items: list[dict] = []

    for month, titles in PLAN.items():
        items = month_to_items(month, titles)
        path = OUT_DIR / f"{month}.json"
        path.write_text(json.dumps(items, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        all_items.extend(items)
        print(f"{path.name}: {len(items)} тем")

    all_path = OUT_DIR / "all.json"
    all_path.write_text(json.dumps(all_items, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"all.json: {len(all_items)} тем")

    default = OUT_DIR / "май.json"
    root_plan = ROOT / "content_plan.json"
    root_plan.write_text(default.read_text(encoding="utf-8"), encoding="utf-8")
    print(f"content_plan.json <- май.json (по умолчанию)")


if __name__ == "__main__":
    main()
